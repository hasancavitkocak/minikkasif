  static String t(String key) =>
      _strings[AppState.I.lang]?[key] ?? _strings['en']![key] ?? key;

  /// Bir cümlenin kayıtlı seslendirme adı (bkz. docs/seslendirme.md);
  /// cümle çeviri tablosunda yoksa null. Övgüler `praise_1`, `praise_2`...
  static String? voiceKey(String text) {
    final table = _strings[AppState.I.lang] ?? _strings['en']!;
    for (final entry in table.entries) {
      if (entry.value == text) return entry.key;
    }
    // Sayılar: `num_1`, `num_2`...
    if (int.tryParse(text) != null) return 'num_$text';
    final praises = (table['praise'] ?? '').split('|');
    final i = praises.indexOf(text);
    return i < 0 ? null : 'praise_${i + 1}';
  }

  static String get ttsCode => languages[AppState.I.lang]?.ttsCode ?? 'en-US';

  static final _rng = Random();

  /// Rastgele bir övgü cümlesi.
  static String praise() {
    final options = t('praise').split('|');
    return options[_rng.nextInt(options.length)];
  }

